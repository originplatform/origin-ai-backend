"""Central Orchestrator Agent for ORIGIN AI."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from app.agents.base import BaseAgent
from app.core.logging import get_logger
from app.graphs.state import OriginState, PlanStep
from app.services.llm_service import llm_service

logger = get_logger("origin.agents.orchestrator")


class PlanStepSchema(BaseModel):
    step_number: int
    agent_name: str
    action: str
    tool_id: Optional[str] = None
    input_params: Dict[str, Any] = Field(default_factory=dict)
    dependencies: List[int] = Field(default_factory=list)


class OrchestratorPlanOutput(BaseModel):
    intent: str
    objective: str
    selected_agents: List[str]
    selected_tools: List[str]
    steps: List[PlanStepSchema]


class OrchestratorAgent(BaseAgent):
    """Central decision-making agent that plans, routes, and delegates tasks."""

    name = "Orchestrator Agent"
    description = "Deconstructs natural-language commands into structured agentic plans, selecting approved agents and tools."
    system_prompt = (
        "You are the Lead Orchestrator for ORIGIN AI. "
        "Your task is to analyze user requests, determine intent and concrete objectives, "
        "and generate a step-by-step execution plan selecting only from registered agents and approved tools."
    )
    allowed_tools = []

    def _generate_deterministic_plan(self, user_command: str) -> OrchestratorPlanOutput:
        """Robust deterministic planner for offline, test, or fallback execution."""
        cmd_lower = user_command.lower()

        # Case 1: Report generation (PDF, DOCX, TXT)
        if any(w in cmd_lower for w in ["report", "pdf", "docx", "document", "research"]):
            topic = "Autonomous AI Agents"
            if "about" in cmd_lower:
                topic = user_command.split("about", 1)[1].split("and", 1)[0].strip()

            steps = [
                PlanStepSchema(
                    step_number=1,
                    agent_name="Research Agent",
                    action=f"Research technical background and architectures for {topic}",
                    tool_id="web_search",
                    input_params={"query": f"{topic} architecture and systems", "max_results": 4},
                    dependencies=[],
                )
            ]

            step_num = 2
            selected_tools = ["web_search"]
            selected_agents = ["Research Agent", "Document Agent", "Verification Agent"]

            needs_docx = "docx" in cmd_lower or "word" in cmd_lower or ("pdf" not in cmd_lower and "txt" not in cmd_lower)
            needs_pdf = "pdf" in cmd_lower or ("docx" not in cmd_lower and "txt" not in cmd_lower)
            needs_txt = "txt" in cmd_lower or "text" in cmd_lower

            # Default to both if both requested or general report
            if not needs_docx and not needs_pdf and not needs_txt:
                needs_docx = True
                needs_pdf = True

            clean_topic = topic.strip().rstrip(".").title()

            if needs_docx:
                steps.append(
                    PlanStepSchema(
                        step_number=step_num,
                        agent_name="Document Agent",
                        action="Create structured DOCX report",
                        tool_id="create_docx",
                        input_params={
                            "title": f"Report: {clean_topic}",
                            "subtitle": "Generated by ORIGIN AI Autonomous Operator",
                            "filename": f"{clean_topic.lower().replace(' ', '_')[:32]}_report.docx",
                            "sections": [],
                        },
                        dependencies=[1],
                    )
                )
                selected_tools.append("create_docx")
                step_num += 1

            if needs_pdf:
                steps.append(
                    PlanStepSchema(
                        step_number=step_num,
                        agent_name="Document Agent",
                        action="Create styled PDF report",
                        tool_id="create_pdf",
                        input_params={
                            "title": f"Report: {clean_topic}",
                            "author": "ORIGIN AI Operator",
                            "filename": f"{clean_topic.lower().replace(' ', '_')[:32]}_report.pdf",
                            "sections": [],
                        },
                        dependencies=[1],
                    )
                )
                selected_tools.append("create_pdf")
                step_num += 1

            # Verification step
            steps.append(
                PlanStepSchema(
                    step_number=step_num,
                    agent_name="Verification Agent",
                    action="Verify generated files exist in workspace and contain valid content",
                    tool_id=None,
                    input_params={},
                    dependencies=list(range(2, step_num)),
                )
            )

            return OrchestratorPlanOutput(
                intent="Research and generate publication-grade documentation",
                objective=f"Research {clean_topic}, compile findings, generate requested files, and verify workspace persistence.",
                selected_agents=selected_agents,
                selected_tools=selected_tools,
                steps=steps,
            )

        # Case 2: File search & email drafting
        elif any(w in cmd_lower for w in ["email", "draft", "mail", "send"]):
            target_query = "report"
            if "find" in cmd_lower and "in my workspace" in cmd_lower:
                part = cmd_lower.split("find", 1)[1].split("in my workspace", 1)[0].strip()
                if part:
                    target_query = part

            steps = [
                PlanStepSchema(
                    step_number=1,
                    agent_name="File Management Agent",
                    action=f"Locate file matching '{target_query}' in workspace",
                    tool_id="search_workspace_files",
                    input_params={"query": target_query},
                    dependencies=[],
                ),
                PlanStepSchema(
                    step_number=2,
                    agent_name="Communication Agent",
                    action="Prepare email draft attaching the located file",
                    tool_id="draft_email",
                    input_params={
                        "to_email": "recipient@example.com",
                        "subject": f"Project Report: {target_query.title()}",
                        "body": "Please find attached the requested report.",
                        "attachments": [],
                    },
                    dependencies=[1],
                ),
                PlanStepSchema(
                    step_number=3,
                    agent_name="Verification Agent",
                    action="Verify email draft and attachments readiness",
                    tool_id=None,
                    input_params={},
                    dependencies=[1, 2],
                ),
            ]

            return OrchestratorPlanOutput(
                intent="Workspace file discovery and email draft preparation",
                objective=f"Locate '{target_query}' in authorized workspace, prepare verified draft with attachment, and preserve safety gate for external sending.",
                selected_agents=["File Management Agent", "Communication Agent", "Verification Agent"],
                selected_tools=["search_workspace_files", "draft_email"],
                steps=steps,
            )

        # Case 3: Generic fallback
        steps = [
            PlanStepSchema(
                step_number=1,
                agent_name="Research Agent",
                action=f"Analyze and process instruction: {user_command}",
                tool_id="web_search",
                input_params={"query": user_command, "max_results": 3},
                dependencies=[],
            ),
            PlanStepSchema(
                step_number=2,
                agent_name="Document Agent",
                action="Summarize execution in workspace text document",
                tool_id="create_txt",
                input_params={"filename": "task_summary.txt", "content": f"Task execution record for: {user_command}"},
                dependencies=[1],
            ),
            PlanStepSchema(
                step_number=3,
                agent_name="Verification Agent",
                action="Confirm task completion and output validation",
                tool_id=None,
                input_params={},
                dependencies=[1, 2],
            ),
        ]

        return OrchestratorPlanOutput(
            intent="Process user instruction and persist execution summary",
            objective=f"Execute command: '{user_command}'",
            selected_agents=["Research Agent", "Document Agent", "Verification Agent"],
            selected_tools=["web_search", "create_txt"],
            steps=steps,
        )

    async def create_plan(self, user_command: str) -> OrchestratorPlanOutput:
        """Generates structured execution plan via LLM or deterministic fallback."""
        prompt = (
            f"User Command: {user_command}\n"
            "Generate an execution plan with intent, objective, selected agents, selected tools, and sequential steps."
        )
        fallback = self._generate_deterministic_plan(user_command).model_dump()

        try:
            plan = await llm_service.generate_structured(
                prompt=prompt,
                response_model=OrchestratorPlanOutput,
                system_prompt=self.system_prompt,
                deterministic_fallback=fallback,
            )
            return plan
        except Exception as exc:
            logger.warning(f"Using fallback plan generator due to: {exc}")
            return self._generate_deterministic_plan(user_command)

    async def process(self, state: OriginState, context: Optional[Dict[str, Any]] = None) -> OriginState:
        """Orchestrator node execution: understands intent and populates plan."""
        logger.info(f"Orchestrator planning task '{state.task_id}': {state.user_command}")
        plan_output = await self.create_plan(state.user_command)

        state.intent = plan_output.intent
        state.objective = plan_output.objective
        state.selected_agents = plan_output.selected_agents
        state.selected_tools = plan_output.selected_tools
        state.execution_plan = [
            PlanStep(
                step_number=s.step_number,
                agent_name=s.agent_name,
                action=s.action,
                tool_id=s.tool_id,
                input_params=s.input_params,
                dependencies=s.dependencies,
                status="PENDING",
            )
            for s in plan_output.steps
        ]
        state.current_step_index = 0
        state.status = "PLANNING"
        return state


orchestrator_agent = OrchestratorAgent()

