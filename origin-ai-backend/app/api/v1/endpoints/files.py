"""Files API endpoints for browsing and downloading generated artifacts."""

import os
from pathlib import Path
from typing import List
from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session
from app.core.logging import get_logger
from app.core.security import PathSecurity, SecurityError, sanitize_filename
from app.db.models.file import GeneratedFile
from app.db.session import get_db
from app.schemas.file import FileMetadataResponse

logger = get_logger("origin.api.files")
router = APIRouter()


@router.get("/files", response_model=List[FileMetadataResponse], summary="List Workspace Files")
def list_files(db: Session = Depends(get_db)):
    """Catalog of all files generated by tasks and stored in the workspace."""
    files = db.query(GeneratedFile).order_by(GeneratedFile.created_at.desc()).all()
    results = []
    for f in files:
        results.append(
            FileMetadataResponse(
                id=f.id,
                task_id=f.task_id,
                filename=f.filename,
                file_path=f.file_path,
                file_type=f.file_type,
                file_size_bytes=f.file_size_bytes,
                mime_type=f.mime_type,
                file_hash=f.file_hash,
                download_url=f"/api/v1/files/{f.id}/download",
                created_at=f.created_at,
            )
        )
    return results


@router.get("/files/{file_id}/download", summary="Download Generated File")
def download_file(file_id: str, db: Session = Depends(get_db)):
    """Streams authorized generated file to the user."""
    file_rec = db.query(GeneratedFile).filter(GeneratedFile.id == file_id).first()
    if not file_rec:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"File record '{file_id}' not found.",
        )

    try:
        safe_path = PathSecurity.resolve_safe_path(file_rec.filename, allow_create_parent=False)
        if not safe_path.is_file():
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Physical file for '{file_rec.filename}' is missing on disk.",
            )

        return FileResponse(
            path=str(safe_path),
            filename=file_rec.filename,
            media_type=file_rec.mime_type,
        )
    except SecurityError as sec_err:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail=str(sec_err))


@router.get("/files/raw/{filename}", summary="Download Workspace File by Name")
def download_file_by_name(filename: str):
    """Direct safe file download by filename."""
    try:
        safe_name = sanitize_filename(filename)
        safe_path = PathSecurity.resolve_safe_path(safe_name, allow_create_parent=False)
        if not safe_path.is_file():
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"File '{filename}' not found.",
            )

        mime_types = {
            ".pdf": "application/pdf",
            ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            ".txt": "text/plain",
            ".json": "application/json",
            ".csv": "text/csv",
        }
        mime = mime_types.get(safe_path.suffix.lower(), "application/octet-stream")

        return FileResponse(
            path=str(safe_path),
            filename=safe_path.name,
            media_type=mime,
        )
    except SecurityError as sec_err:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail=str(sec_err))

